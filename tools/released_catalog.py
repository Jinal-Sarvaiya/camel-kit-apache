"""Rebuild the pre-ledger catalog from published camel-kit-core CLI classpaths.

Pass a directory containing <version>/cp files (Maven dependency:build-classpath)
for io.github.luigidemasi:camel-kit-core at each version below. Run from the repository root with Java 21 or later.
The optional workspace directory retains the generated installs for upgrade tests.
"""
import argparse
import hashlib
import os
from pathlib import Path
import subprocess
import tempfile

RELEASES = ("0.2.0", "0.3.0", "0.3.1", "0.4.0", "0.4.1")
HOSTS = {"antigravity": ".agents", "bob2": ".bob", "claude": ".claude",
         "codex": ".agents", "copilot": ".github", "opencode": ".opencode",
         "pi": ".pi", "qwen": ".qwen"}
OUTPUT = Path("kit/camel-kit-core/src/main/resources/workflow/pre-ledger-catalog.tsv")


def capture(classpaths, work):
    entries = {}
    for version in RELEASES:
        classpath = (classpaths / version / "cp").read_text().strip()
        for host, folder in HOSTS.items():
            old_cli = version < "0.4"
            if old_cli and host not in ("bob2", "claude"):
                continue
            agent = "bob" if old_cli and host == "bob2" else host
            for prefix in ("camel kit", "camel-kit"):
                project = work / version / host / prefix
                project.mkdir(parents=True)
                # The released CLI inspects the OS command line. Keep artifact paths containing "camel-kit" off it.
                command = ["java", "-Dlauncher=" + prefix, "io.github.luigidemasi.camelkit.CamelKitMain",
                           "init", "--here", "--ai", agent, "--no-fetch"]
                result = subprocess.run(command, cwd=project, env=dict(os.environ, CLASSPATH=classpath),
                                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
                if result.returncode:
                    raise RuntimeError(f"{version} {agent}: {result.stdout}")
                if not old_cli:
                    config = (project / ".camel-kit/config.properties").read_text()
                    assert f"project.command-prefix={prefix}\n" in config, (project, config)
                directories = {"skills": "skills", "commands": "prompts" if host == "pi" else "commands"}
                for kind, directory in directories.items():
                    root = project / folder / directory
                    for asset in sorted(root.rglob("*")):
                        if asset.is_file():
                            path = kind + "/" + asset.relative_to(root).as_posix()
                            # All historical catalog entries are Markdown. Reject an unexpected binary.
                            assert asset.suffix == ".md", asset
                            data = asset.read_text(encoding="utf-8").encode("utf-8")
                            digest = hashlib.sha256(data).hexdigest()
                            entries.setdefault((path, digest), set()).add(host)
    return entries


def historic_guides(entries):
    # These three guides were retired between releases. The old installer only rewrote
    # slash invocations for Codex. None of the guides had a version substitution or a trait.
    revision = "8a10fd13c6df94709e669b9c256192b8eb66e24f"
    for guide in ("auto-fix-loop", "oversight-matrix", "state-management"):
        path = f"skills/camel-ship/guides/{guide}.md"
        data = subprocess.check_output(["git", "show", f"{revision}:camel-kit-core/src/main/resources/{path}"])
        for host in HOSTS.keys() - {"antigravity"}:
            rendered = data.replace(b"/camel-ship`", b"$camel-ship`") if host == "codex" else data
            entries.setdefault((path, hashlib.sha256(rendered).hexdigest()), set()).add(host)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("classpaths", type=Path)
    parser.add_argument("--workspaces", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as temp:
        entries = capture(args.classpaths.resolve(), args.workspaces or Path(temp))
    historic_guides(entries)
    lines = ["# Known pre-ledger installs. Generated by tools/released_catalog.py.",
             "# catalog path\tSHA-256\thosts (* = all eight historical targets)"]
    for (path, digest), hosts in sorted(entries.items()):
        names = "*" if hosts == HOSTS.keys() else ",".join(sorted(hosts))
        lines.append(f"{path}\t{digest}\t{names}")
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
